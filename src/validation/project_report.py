
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[2]
PATIENT_FILE = (
    PROJECT_ROOT / "data" / "processed"
    / "synthetic_patients.csv"
)
WAVEFORM_FILE = (
    PROJECT_ROOT / "data" / "processed"
    / "patient_waveforms.csv"
)
KS_FILE = (
    PROJECT_ROOT / "outputs" / "reports"
    / "ks_validation.csv"
)
CORRELATION_FILE = (
    PROJECT_ROOT / "outputs" / "reports"
    / "correlation_validation.csv"
)
OUTPUT_FILE = (
    PROJECT_ROOT / "outputs" / "reports"
    / "project_summary.txt"
)


def generate_project_report():
    patients = pd.read_csv(PATIENT_FILE)
    waveforms = pd.read_csv(WAVEFORM_FILE)
    ks = pd.read_csv(KS_FILE)

    class_counts = patients["class"].value_counts().sort_index()
    points_per_patient = waveforms.groupby("patient_id").size()

    ks_passes = int(ks["pass_at_0_05"].sum())
    ks_total = len(ks)
    ks_failures = ks_total - ks_passes

    lines = [
        "CARDIOSYNTH — PROJECT SUMMARY",
        "=" * 50,
        "",
        "PROJECT OVERVIEW",
        "Synthetic cardiovascular dataset generation and statistical validation.",
        "Generated data is illustrative and is not real patient data.",
        "",
        "PATIENT DATASET",
        f"Total records: {len(patients)}",
        f"Unique patient IDs: {patients['patient_id'].nunique()}",
        f"Features: {len(patients.columns) - 2}",
        "",
        "RECORDS PER CLASS",
    ]

    for patient_class, count in class_counts.items():
        lines.append(f"{patient_class}: {count}")

    lines.extend([
        "",
        "WAVEFORM DATASET",
        f"Total waveform points: {len(waveforms)}",
        f"Patients with waveforms: {len(points_per_patient)}",
        f"Minimum points per patient: {points_per_patient.min()}",
        f"Maximum points per patient: {points_per_patient.max()}",
        "",
        "KS DISTRIBUTION TESTS",
        f"Tests performed: {ks_total}",
        f"Not rejected at alpha=0.05: {ks_passes}",
        f"Rejected at alpha=0.05: {ks_failures}",
        "",
        "LIMITATIONS",
        "- Reference parameters are illustrative estimates.",
        "- KS test results do not establish clinical validity.",
        "- Copula dependencies are assumed, not clinically validated.",
        "- Waveforms are mathematical demonstrations, not measured signals.",
        "- Statistical tests may be affected by clipping and consistency corrections.",
        "",
        "CORRELATION REPORT",
        f"Correlation report exists: {CORRELATION_FILE.exists()}",
        "",
        "Generated by CardioSynth.",
    ])

    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_FILE.write_text("\n".join(lines), encoding="utf-8")

    print("Project report generated successfully!")
    print("Saved to:", OUTPUT_FILE)
    print("\n".join(lines))


if __name__ == "__main__":
    generate_project_report()
